#!/usr/bin/env python3
"""Pre-registered candidate H1: co-located magnetic + gravity horizontal-gradient ridges, off-catalogue.

PRE-REGISTRATION (fixed before any evaluation of this candidate; do not tune on the holdout):
  layers      : tmi_hg (total magnetic intensity horizontal gradient) and
                iso_grav_anom_hg (isostatic gravity horizontal gradient), both from training_features.tif
  signature   : a dot is kept only where BOTH independent potential-field edge maps are high
                (score S = min(robust-z(tmi_hg), robust-z(iso_grav_anom_hg)))
  non-fault   : lithologic contacts, dikes and magnetic/gravity edges from cover or topography
  suppression : keep local maxima of S in a 7x7 window (non-maximum suppression, one dot per ridge cell)
  catalogue   : remove every dot within 3 px (300 m) of a catalogue fault pixel in labels.tif
  budget      : top N = 20,000 dots by S (below the 22,163 pigeonhole bound used by the repo's gate)
  output      : exact binary {0,1}; written by the repo's canonical submission_writer (zeros outside)

Leakage canary: each feature alone, AUC against catalogue positives inside the footprint (labels==1
vs labels==0). AUC > 0.90 would mean leakage until proven otherwise.

This script writes the raw emission mask and a canary receipt; evaluation is a separate step.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import rasterio
from scipy.ndimage import distance_transform_edt, maximum_filter
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "src"))
from gems32.paths import data_dir  # noqa: E402
sys.path.insert(0, str(ROOT / "scripts"))

N_DOTS = 20000
NMS_WINDOW = 7
RADIUS_PX = 3.0
SEED = 20261029
CANARY_FEATURES = ("tmi_hg", "iso_grav_anom_hg", "tc", "tmi_vg", "iso_grav_anom_vg", "det_elev_slope")
OUT_NPY = ROOT / ".cache" / "candidates" / "h1_mask.npy"
OUT_JSON = ROOT / "docs" / "data" / "h1-candidate-receipt.json"
OUT_TIF_DIR = ROOT / ".cache" / "candidates" / "h1"
TIMESTAMP_TAG = "20261029T180906Z"  # fixed so the regenerated bytes can be compared with the recorded SHA-256


def band_index(ds, name: str) -> int:
    for i, d in enumerate(ds.descriptions, start=1):
        if d and d.split(" - ")[0] == name:
            return i
    raise KeyError(f"band {name!r} not found")


def robust_z(x: np.ndarray, valid: np.ndarray) -> np.ndarray:
    v = x[valid]
    med = np.median(v)
    mad = np.median(np.abs(v - med)) * 1.4826
    out = np.zeros_like(x, dtype=np.float32)
    out[valid] = ((v - med) / (mad if mad > 0 else 1.0)).astype(np.float32)
    return out


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> int:
    ddir = data_dir()
    with rasterio.open(ddir / "sample_submission.tif") as tpl:
        foot_tpl = np.isfinite(tpl.read(1))
    with rasterio.open(ddir / "labels.tif") as ds:
        labels_raw = ds.read(1)
    foot = labels_raw != -1
    if not np.array_equal(foot, foot_tpl):
        raise SystemExit("labels.tif footprint (!= -1) does not match sample_submission finite footprint")
    cat = (labels_raw == 1) & foot

    feats = {}
    with rasterio.open(ddir / "training_features.tif") as ds:
        nodata = ds.nodata
        for name in CANARY_FEATURES:
            i = band_index(ds, name)
            a = ds.read(i).astype(np.float64)
            ok = np.isfinite(a) & (a != nodata) & foot
            feats[name] = (a, ok, i)

    # 1) per-feature leakage canary (each feature alone)
    rng = np.random.default_rng(SEED)
    canary = {}
    pos = np.argwhere(cat)
    neg_all = np.argwhere(foot & ~cat)
    neg = neg_all[rng.choice(len(neg_all), size=min(200000, len(neg_all)), replace=False)]
    pos_s = pos[rng.choice(len(pos), size=min(200000, len(pos)), replace=False)]
    for name, (a, ok, band) in feats.items():
        ps = [p for p in pos_s if ok[p[0], p[1]]]
        ns = [p for p in neg if ok[p[0], p[1]]]
        if not ps or not ns:
            canary[name] = dict(band=band, auc=None)
            continue
        y = np.r_[np.ones(len(ps)), np.zeros(len(ns))]
        s = np.r_[[a[p[0], p[1]] for p in ps], [a[p[0], p[1]] for p in ns]]
        auc = float(roc_auc_score(y, s))
        canary[name] = dict(band=band, auc=round(auc, 6), n_pos=len(ps), n_neg=len(ns),
                            leakage_suspect=bool(max(auc, 1 - auc) > 0.90))

    # 2) candidate score S = min of two independent edge maps
    mag, okm, bm = feats["tmi_hg"]
    grav, okg, bg = feats["iso_grav_anom_hg"]
    valid = foot & okm & okg
    zm = robust_z(mag, valid)
    zg = robust_z(grav, valid)
    S = np.where(valid, np.minimum(zm, zg), -np.inf)

    # 3) catalogue exclusion (3 px) and local-maximum suppression
    d_cat = distance_transform_edt(~cat)
    S = np.where(d_cat > RADIUS_PX, S, -np.inf)
    nms = maximum_filter(np.where(np.isfinite(S), S, -1e9), size=NMS_WINDOW)
    keep = np.isfinite(S) & (S >= nms)

    # 4) top-N budget by S
    cand = np.argwhere(keep)
    vals = S[cand[:, 0], cand[:, 1]]
    order = np.argsort(-vals, kind="stable")[:N_DOTS]
    sel = cand[order]
    mask = np.zeros(foot.shape, np.uint8)
    mask[sel[:, 0], sel[:, 1]] = 1

    OUT_NPY.parent.mkdir(parents=True, exist_ok=True)
    np.save(OUT_NPY, mask)
    rec = dict(
        schema_version=1,
        candidate="H1 magnetic+gravity horizontal-gradient ridge, off-catalogue, NMS, 20k",
        preregistered_parameters=dict(layers=["tmi_hg", "iso_grav_anom_hg"], score="min(robust_z)",
                                      nms_window=NMS_WINDOW, catalogue_exclusion_px=RADIUS_PX,
                                      budget=N_DOTS, seed=SEED),
        n_candidate_cells_after_nms=int(cand.shape[0]),
        n_dots=int(mask.sum()),
        footprint_cells=int(foot.sum()),
        catalogue_positive_cells=int(cat.sum()),
        leakage_canary=canary,
        mask_npy=str(OUT_NPY.relative_to(ROOT)),
        mask_npy_sha256=sha256(OUT_NPY),
    )
    # Write the BLOCKED research TIFF through the canonical writer into the gitignored cache.
    # It is deliberately NOT placed under docs/ (the repo's saved-byte audit enumerates every docs/**/*.tif).
    from submission_writer import write_validated_submission  # noqa: E402
    note = "h1-ridge-offcat-nms: mag+grav edge ridges >3px from catalogue, 14k dots"
    meta = dict(candidate_id="gemsdoekarage3-h1-ridge-offcat-nms-14k",
                description="Pre-registered H1 (scripts/build_h1_candidate.py); BLOCKED by literal uniqueness",
                submission_note_zeros=note, submission_note_nan=note)
    bundle = write_validated_submission(mask, slug="gemsdoekarage3-h1-ridge-offcat-nms-14k", candidate_meta=meta,
                                        ddir=ddir, out_dir=OUT_TIF_DIR, timestamp_tag=TIMESTAMP_TAG)
    rec["blocked_tif"] = dict(path=str((OUT_TIF_DIR / bundle["zeros_tif"]["filename"]).relative_to(ROOT)),
                              sha256=bundle["zeros_tif"]["sha256"], status="BLOCKED - DO NOT SUBMIT",
                              reason="99.45% of dots within 3 px of 13GEMSDOE lattice (literal limit 70%)")
    OUT_JSON.write_text(json.dumps(rec, indent=2, allow_nan=False) + "\n")
    print(json.dumps(rec, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
